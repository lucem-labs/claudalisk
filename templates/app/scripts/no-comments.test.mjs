import assert from 'node:assert/strict';
import { test } from 'node:test';
import { findCommentLines, findComments, parseArgs, syntaxOf, trackedFiles } from './no-comments.mjs';

test('covers every file type CLA-0035 lists', () => {
  const covered = {
    'backend/App/Program.cs': 'csharp',
    'frontend/src/main.tsx': 'script',
    'frontend/src/app.ts': 'script',
    'scripts/deploy.mjs': 'script',
    'frontend/src/index.css': 'css',
    'backend/fix.sql': 'sql',
    'backend/App/App.csproj': 'markup',
    'backend/Directory.Build.props': 'markup',
    'backend/App.slnx': 'markup',
    'frontend/index.html': 'markup',
    'compose.base.yml': 'hash',
    '.github/workflows/ci.yml': 'hash',
    '.gitignore': 'hash',
    'backend/Dockerfile': 'dockerfile',
    'frontend/Dockerfile.dev': 'dockerfile',
    'frontend/tsconfig.json': 'json',
  };
  for (const [path, syntax] of Object.entries(covered)) assert.equal(syntaxOf(path), syntax, path);
  assert.equal(syntaxOf('docs/README.md'), undefined);
  assert.equal(syntaxOf('design/logo.png'), undefined);
});

test('finds line and block comments in scripts', () => {
  assert.deepEqual(findCommentLines('const a = 1;\n// why\nconst b = 2; /* note */\n', 'a.ts'), [2, 3]);
  assert.deepEqual(findCommentLines('/**\n * Adds.\n */\nexport const add = 1;\n', 'a.ts'), [1]);
});

test('ignores comment markers inside strings, templates and regular expressions', () => {
  const code = [
    "const url = 'http://localhost';",
    'const glob = "src/**/*.ts";',
    'const t = `a // b ${x ? `/* c */` : "//"} d`;',
    'const re = /\\/\\*.*\\*\\//g;',
    'const half = a / b / c;',
    'if (ok) return /\\/\\//.test(s);',
    '',
  ].join('\n');
  assert.deepEqual(findCommentLines(code, 'a.mjs'), []);
});

test('a comment after a template expression still counts', () => {
  assert.deepEqual(findCommentLines('const t = `${a}`; // why\n', 'a.ts'), [1]);
});

test('an apostrophe in JSX text does not hide the next line', () => {
  assert.deepEqual(findCommentLines("<p>Don't</p>\n// why\n", 'a.tsx'), [2]);
});

test('lint suppressions, references and shebangs are directives', () => {
  const code = [
    '#!/usr/bin/env node',
    '/// <reference types="vite/client" />',
    '// eslint-disable-next-line no-console',
    '// oxlint-disable-next-line no-console',
    '// @ts-expect-error',
    '',
  ].join('\n');
  assert.deepEqual(findCommentLines(code, 'a.ts'), []);
  assert.deepEqual(findCommentLines('// ReSharper disable once InconsistentNaming\nclass A {}\n', 'A.cs'), []);
});

test('generated files are skipped', () => {
  assert.deepEqual(findCommentLines('/**\n * This file was auto-generated by openapi-typescript.\n */\n', 'schema.ts'), []);
  assert.deepEqual(findCommentLines('// <auto-generated />\nusing System;\n', 'Init.cs'), []);
  assert.deepEqual(findCommentLines('// anything\n', 'Migrations/20261024000000_Init.Designer.cs'), []);
  assert.deepEqual(findCommentLines('// anything\n', 'Migrations/AppDbContextModelSnapshot.cs'), []);
});

test('finds C# comments and XML doc comments outside strings', () => {
  const code = [
    '/// <summary>Adds.</summary>',
    'var a = "// no";',
    'var b = @"C:\\// no "" still";',
    'var c = $"{x} /* no */";',
    'var d = """',
    '  // no',
    '  """;',
    "var e = '/';",
    'var f = 1; // yes',
    '#pragma warning disable CS1591',
    '',
  ].join('\n');
  assert.deepEqual(findCommentLines(code, 'A.cs'), [1, 9]);
});

test('finds CSS block comments but not URLs', () => {
  assert.deepEqual(findCommentLines('a { background: url(http://x/y.png); }\n/* why */\n', 'a.css'), [2]);
  assert.deepEqual(findCommentLines('a::before { content: "/* no */"; }\n', 'a.css'), []);
});

test('finds SQL comments outside strings and dollar quotes', () => {
  const code = [
    "select '-- no', 'it''s /* no */' from t where id = $1;",
    'do $$ begin -- no',
    'end $$;',
    '-- yes',
    'select 1; /* yes */',
    '',
  ].join('\n');
  assert.deepEqual(findCommentLines(code, 'fix.sql'), [4, 5]);
});

test('finds comments in JSON config', () => {
  assert.deepEqual(findCommentLines('{\n  "url": "http://x", // why\n  "glob": "**/*"\n}\n', 'tsconfig.json'), [2]);
});

test('finds markup comments in project files and HTML', () => {
  assert.deepEqual(findCommentLines('<Project>\n  <!-- why -->\n</Project>\n', 'App.csproj'), [2]);
  assert.deepEqual(findCommentLines('<html>\n<!-- why -->\n</html>\n', 'index.html'), [2]);
});

test('finds YAML comments outside quoted values', () => {
  const code = [
    '# why',
    'name: ci',
    "color: '#fff'",
    'title: "a # b"',
    'url: https://example.com/#anchor',
    'steps:',
    '  - run: node scripts/verify.mjs # why',
    '    with:',
    "      note: it's # why",
    '',
  ].join('\n');
  assert.deepEqual(findCommentLines(code, 'ci.yml'), [1, 7, 9]);
});

test('finds Dockerfile comments but not parser directives or mid-line hashes', () => {
  const code = ['# syntax=docker/dockerfile:1', 'FROM node:22', '# why', 'RUN echo "#1"', '  # indented', ''].join('\n');
  assert.deepEqual(findCommentLines(code, 'Dockerfile'), [3, 5]);
});

test('the inheritdoc tag that EF Core writes into migrations is a directive', () => {
  assert.deepEqual(findCommentLines('    /// <inheritdoc />\n    protected override void Up() {}\n', '20261024000000_Init.cs'), []);
  assert.deepEqual(findCommentLines('/// <inheritdoc /> because\n', 'A.cs'), [1]);
});

test('findComments lists offenders as path:line and skips uncovered files', () => {
  const files = { 'a.ts': '// why\n', 'b.md': '<!-- docs -->\n', 'c.cs': 'class C {}\r\n// why\r\n' };
  assert.deepEqual(findComments(Object.keys(files), (f) => files[f]), ['a.ts:1', 'c.cs:2']);
});

test('findComments leaves out the skipped files and folders', () => {
  const files = { 'src/api/schema.ts': '// why\n', 'design/a.html': '<!-- why -->\n', 'designer.ts': '// why\n' };
  assert.deepEqual(findComments(Object.keys(files), (f) => files[f], ['src/api/schema.ts', 'design']), ['designer.ts:1']);
});

test('parseArgs reads the root and every --skip', () => {
  assert.deepEqual(parseArgs(['--skip', 'design/', '--skip', 'src\\api\\schema.ts']), { root: '.', skip: ['design', 'src/api/schema.ts'] });
  assert.deepEqual(parseArgs(['app']), { root: 'app', skip: [] });
  assert.throws(() => parseArgs(['--fix']), /Unknown argument: --fix/);
});

test('trackedFiles asks git for the tracked files with an argument array', () => {
  const calls = [];
  const run = (command, args, options) => {
    calls.push([command, args, options.cwd]);
    return 'a.ts\0dir/b.cs\0';
  };
  assert.deepEqual(trackedFiles('/repo', run), ['a.ts', 'dir/b.cs']);
  assert.deepEqual(calls, [['git', ['ls-files', '-z'], '/repo']]);
});
