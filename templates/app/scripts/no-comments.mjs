import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { basename, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SYNTAX_BY_EXTENSION = {
  '.ts': 'script',
  '.tsx': 'script',
  '.mts': 'script',
  '.cts': 'script',
  '.js': 'script',
  '.jsx': 'script',
  '.mjs': 'script',
  '.cjs': 'script',
  '.cs': 'csharp',
  '.css': 'css',
  '.sql': 'sql',
  '.json': 'json',
  '.jsonc': 'json',
  '.csproj': 'markup',
  '.props': 'markup',
  '.targets': 'markup',
  '.slnx': 'markup',
  '.config': 'markup',
  '.xml': 'markup',
  '.html': 'markup',
  '.yml': 'yaml',
  '.yaml': 'yaml',
  '.toml': 'yaml',
};

export const SYNTAX_BY_NAME = {
  '.gitignore': 'ignore',
  '.gitattributes': 'ignore',
  '.dockerignore': 'ignore',
  '.editorconfig': 'ini',
};

const SCRIPT_DIRECTIVE = /^(?:\/\/\/?|\/\*)\s*(?:(?:eslint|oxlint)-(?:disable|enable)(?:-next-line|-line)?(?:\s|\*\/|$)|@ts-(?:expect-error|ignore|nocheck|check)\b|<reference\s[^>]*\/>\s*$|ReSharper (?:disable|restore)\s)/;
const INHERITDOC = /^\/\/\/\s*<inheritdoc\s*\/>\s*$/;
const MIGRATION_FILE = /(?:^|\/)Migrations\/\d{14}_[^/]+\.cs$/;
const DOCKER_PARSER_DIRECTIVE = /^#\s*(?:syntax|escape|check)\s*=\s*\S+\s*$/i;
const SCALAR_START = /(?:^\s*(?:-\s+)?|[:-]\s+|[[{,]\s*)$/;
const GENERATED_HEADER = /^\s*(?:\/\/|\/\*+|#|--|<!--)[\s*]*(?:<auto-generated|this file (?:is|was) auto-?generated|@generated\b)/i;
const GENERATED_NAMES = [/\.Designer\.cs$/, /ModelSnapshot\.cs$/];
const BLOCK_SCALAR = /(?:^|[\s:-])[|>][-+0-9]*\s*(?:#.*)?$/;
const DOLLAR_TAG = /^\$(?:[A-Za-z_][A-Za-z0-9_]*)?\$/;
const USAGE = 'Usage: node scripts/no-comments.mjs [<root>] [--skip <path>]...';
const REGEX_AFTER = new Set([...'(,=:[!&|?{;+-*%>~^']);
const REGEX_AFTER_WORDS = new Set(['return', 'typeof', 'case', 'do', 'else', 'in', 'of', 'new', 'delete', 'void', 'throw', 'yield', 'await']);

export function syntaxOf(path) {
  const name = basename(path);
  if (SYNTAX_BY_NAME[name]) return SYNTAX_BY_NAME[name];
  if (name === 'Dockerfile' || name.startsWith('Dockerfile.') || name.endsWith('.Dockerfile')) return 'dockerfile';
  return SYNTAX_BY_EXTENSION[extname(name)];
}

export const isGenerated = (path, text) => GENERATED_NAMES.some((p) => p.test(path)) || GENERATED_HEADER.test(text.replace(/^﻿/, ''));

function lineAt(text, index) {
  let line = 1;
  for (let i = 0; i < index; i++) if (text[i] === '\n') line++;
  return line;
}

const lineFrom = (text, index) => {
  const end = text.indexOf('\n', index);
  return text.slice(index, end < 0 ? undefined : end);
};

function skipQuoted(text, i, quote, { escape, singleLine }) {
  for (let j = i + 1; j < text.length; j++) {
    if (escape && text[j] === '\\') j++;
    else if (singleLine && text[j] === '\n') return j;
    else if (text[j] === quote) return j + 1;
  }
  return text.length;
}

function skipCsharpString(text, i) {
  let start = i;
  while (text[start] === '$' || text[start] === '@') start++;
  const verbatim = text.slice(i, start).includes('@');
  let quotes = 0;
  while (text[start + quotes] === '"') quotes++;
  if (quotes >= 3 && !verbatim) {
    const close = text.indexOf('"'.repeat(quotes), start + quotes);
    return close < 0 ? text.length : close + quotes;
  }
  if (verbatim) {
    for (let j = start + 1; j < text.length; j++) {
      if (text[j] === '"' && text[j + 1] === '"') j++;
      else if (text[j] === '"') return j + 1;
    }
    return text.length;
  }
  return skipQuoted(text, start, '"', { escape: true, singleLine: true });
}

function skipDollarQuoted(text, i) {
  const tag = text.slice(i).match(DOLLAR_TAG)?.[0];
  if (!tag) return i + 1;
  const close = text.indexOf(tag, i + tag.length);
  return close < 0 ? text.length : close + tag.length;
}

function regexAllowed(text, i) {
  let j = i - 1;
  while (j >= 0 && /\s/.test(text[j])) j--;
  if (j < 0) return true;
  if (text[j] === '}' && text.slice(j, i).includes('\n')) return true;
  if ((text[j] === '+' || text[j] === '-') && text[j - 1] === text[j]) return false;
  if (REGEX_AFTER.has(text[j])) return true;
  const word = text.slice(0, j + 1).match(/[A-Za-z_$][\w$]*$/)?.[0];
  return word !== undefined && REGEX_AFTER_WORDS.has(word);
}

function skipRegex(text, i) {
  let inClass = false;
  for (let j = i + 1; j < text.length && text[j] !== '\n'; j++) {
    if (text[j] === '\\') j++;
    else if (text[j] === '[') inClass = true;
    else if (text[j] === ']') inClass = false;
    else if (text[j] === '/' && !inClass) return j + 1;
  }
  return i + 1;
}

function skipTemplate(text, i, templates) {
  for (let j = i; j < text.length; j++) {
    if (text[j] === '\\') j++;
    else if (text[j] === '`') return j + 1;
    else if (text[j] === '$' && text[j + 1] === '{') {
      templates.push(0);
      return j + 2;
    }
  }
  return text.length;
}

function scanCLike(text, { lineComments, regex, csharp, sql, quotes }) {
  const found = [];
  const templates = [];
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    const next = text[i + 1];
    const depth = templates.length ? templates[templates.length - 1] : undefined;
    if (depth === 0 && c === '}') {
      templates.pop();
      i = skipTemplate(text, i + 1, templates);
      continue;
    }
    if (depth !== undefined && c === '{') templates[templates.length - 1]++;
    else if (depth !== undefined && c === '}') templates[templates.length - 1]--;
    if (c === '/' && next === '*') {
      found.push(i);
      const close = text.indexOf('*/', i + 2);
      i = close < 0 ? text.length : close + 2;
    } else if (lineComments.some((marker) => text.startsWith(marker, i))) {
      found.push(i);
      const close = text.indexOf('\n', i);
      i = close < 0 ? text.length : close;
    } else if (csharp && (c === '"' || ((c === '$' || c === '@') && /^[$@]{1,3}"/.test(text.slice(i, i + 4))))) {
      i = skipCsharpString(text, i);
    } else if (sql && c === '$' && !/[\w$]/.test(text[i - 1] ?? '')) {
      i = skipDollarQuoted(text, i);
    } else if (sql && c === "'") {
      const escaped = /[Ee]/.test(text[i - 1] ?? '') && !/[\w$]/.test(text[i - 2] ?? '');
      i = skipQuoted(text, i, c, { escape: escaped, singleLine: false });
    } else if (regex && c === '`') {
      i = skipTemplate(text, i + 1, templates);
    } else if (quotes.includes(c)) {
      i = skipQuoted(text, i, c, { escape: !sql, singleLine: !sql });
    } else if (regex && c === '/' && regexAllowed(text, i)) {
      i = skipRegex(text, i);
    } else {
      i++;
    }
  }
  return found;
}

const indentOf = (line) => line.length - line.trimStart().length;

function scanYaml(text) {
  const found = [];
  let offset = 0;
  let quote;
  let quoteStartsScalar = false;
  let blockIndent;
  for (const line of text.split('\n')) {
    const start = offset;
    offset += line.length + 1;
    if (blockIndent !== undefined) {
      if (!line.trim() || indentOf(line) > blockIndent) continue;
      blockIndent = undefined;
    }
    let comment;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      const boundary = i === 0 || /[\s:[{,]/.test(line[i - 1]);
      if (quote === '"' && c === '\\') i++;
      else if (quote === "'" && c === "'" && line[i + 1] === "'") i++;
      else if (quote && c === quote) quote = undefined;
      else if (!quote && (c === '"' || c === "'") && boundary) {
        quote = c;
        quoteStartsScalar = SCALAR_START.test(line.slice(0, i));
      } else if (!quote && c === '#' && (i === 0 || /\s/.test(line[i - 1]))) {
        comment = i;
        break;
      }
    }
    if (quote && !quoteStartsScalar) quote = undefined;
    if (comment !== undefined && !(start === 0 && comment === 0 && line[1] === '!')) found.push(start + comment);
    if (!quote && BLOCK_SCALAR.test(line.slice(0, comment ?? line.length))) blockIndent = indentOf(line);
  }
  return found;
}

function lineStartComments(text, markers, allowed = () => false) {
  const found = [];
  let offset = 0;
  let leading = true;
  for (const line of text.split('\n')) {
    const trimmed = line.trimStart();
    const isComment = markers.some((m) => trimmed.startsWith(m));
    if (isComment && !(leading && allowed(trimmed))) found.push(offset + indentOf(line));
    if (!isComment || !allowed(trimmed)) leading = false;
    offset += line.length + 1;
  }
  return found;
}

const scanMarkup = (text) => [...text.matchAll(/<!--/g)].map((m) => m.index);

const SCANNERS = {
  script: (text) => scanCLike(text, { lineComments: ['//'], regex: true, quotes: ['"', "'"] }),
  csharp: (text) => scanCLike(text, { lineComments: ['//'], csharp: true, quotes: ["'"] }),
  css: (text) => scanCLike(text, { lineComments: [], quotes: ['"', "'"] }),
  sql: (text) => scanCLike(text, { lineComments: ['--'], sql: true, quotes: ['"'] }),
  json: (text) => scanCLike(text, { lineComments: ['//'], quotes: ['"'] }),
  markup: scanMarkup,
  yaml: scanYaml,
  ignore: (text) => lineStartComments(text, ['#']),
  ini: (text) => lineStartComments(text, ['#', ';']),
  dockerfile: (text) => lineStartComments(text, ['#'], (line) => DOCKER_PARSER_DIRECTIVE.test(line)),
};

function isDirective(syntax, path, comment) {
  if (syntax === 'script' || syntax === 'csharp' || syntax === 'json' || syntax === 'css') {
    if (SCRIPT_DIRECTIVE.test(comment)) return true;
  }
  return syntax === 'csharp' && MIGRATION_FILE.test(path) && INHERITDOC.test(comment);
}

export function findCommentLines(text, path) {
  const syntax = syntaxOf(path);
  if (!syntax || isGenerated(path, text)) return [];
  const normalized = path.replace(/\\/g, '/');
  return [...new Set(SCANNERS[syntax](text)
    .filter((index) => !isDirective(syntax, normalized, lineFrom(text, index).trimEnd()))
    .map((index) => lineAt(text, index)))];
}

export function parseArgs(argv) {
  const options = { root: '.', skip: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--skip') {
      if (!argv[i + 1] || argv[i + 1].startsWith('-')) throw new Error(`--skip needs a path\n${USAGE}`);
      options.skip.push(argv[++i].replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/$/, ''));
    } else if (argv[i].startsWith('-')) throw new Error(`Unknown argument: ${argv[i]}\n${USAGE}`);
    else options.root = argv[i];
  }
  return options;
}

const skipped = (file, skip) => skip.some((path) => file === path || file.startsWith(`${path}/`));

export function findComments(files, read, skip = []) {
  const offenders = [];
  for (const file of files) {
    if (!syntaxOf(file) || skipped(file, skip)) continue;
    for (const line of findCommentLines(read(file).replace(/\r\n/g, '\n'), file)) offenders.push({ file, line });
  }
  return offenders;
}

export function trackedFiles(root, run = execFileSync) {
  return run('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
}

export function main(argv, { list, read, out, err, env }) {
  let options;
  try {
    options = parseArgs(argv);
  } catch (error) {
    err(error.message);
    return 2;
  }
  const offenders = findComments(list(options.root), (file) => read(options.root, file), options.skip);
  if (offenders.length === 0) return 0;
  if (env.GITHUB_ACTIONS === 'true') {
    for (const { file, line } of offenders) out(`::error file=${file},line=${line}::Comment (CLA-0035)`);
  }
  err(`Comments found (CLA-0035):\n${offenders.map(({ file, line }) => `${file}:${line}`).join('\n')}`);
  return 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2), {
    list: (root) => trackedFiles(resolve(root)),
    read: (root, file) => readFileSync(join(resolve(root), file), 'utf8'),
    out: (text) => console.log(text),
    err: (text) => console.error(text),
    env: process.env,
  });
}
