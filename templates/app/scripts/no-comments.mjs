#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { basename, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SYNTAX_BY_EXTENSION = {
  '.ts': 'script',
  '.tsx': 'script',
  '.mts': 'script',
  '.cts': 'script',
  '.js': 'script',
  '.jsx': 'script',
  '.mjs': 'script',
  '.cjs': 'script',
  '.cs': 'csharp',
  '.css': 'css',
  '.sql': 'sql',
  '.json': 'json',
  '.jsonc': 'json',
  '.csproj': 'markup',
  '.props': 'markup',
  '.targets': 'markup',
  '.slnx': 'markup',
  '.config': 'markup',
  '.xml': 'markup',
  '.html': 'markup',
  '.yml': 'hash',
  '.yaml': 'hash',
  '.toml': 'hash',
};

export const SYNTAX_BY_NAME = {
  '.gitignore': 'hash',
  '.gitattributes': 'hash',
  '.dockerignore': 'hash',
  '.editorconfig': 'hash',
};

const DIRECTIVE = /^(?:\/\/\/?|\/\*|#|--)\s*(?:eslint-(?:disable|enable)|oxlint-(?:disable|enable)|@ts-|<reference\b|<inheritdoc\s*\/>\s*$|ReSharper (?:disable|restore)|yaml-language-server:|syntax\s*=|escape\s*=|check\s*=)/;
const GENERATED_HEADER = /^\s*(?:\/\/|\/\*+|#|--|<!--)[\s*]*(?:<auto-generated|this file (?:is|was) auto-?generated|@generated\b)/i;
const GENERATED_NAMES = [/\.Designer\.cs$/, /ModelSnapshot\.cs$/];
const USAGE = 'Usage: node scripts/no-comments.mjs [<root>] [--skip <path>]...';
const REGEX_AFTER =new Set([...'(,=:[!&|?{};+-*%<>~^']);
const REGEX_AFTER_WORDS = new Set(['return', 'typeof', 'case', 'do', 'else', 'in', 'of', 'new', 'delete', 'void', 'throw', 'yield', 'await']);

export function syntaxOf(path) {
  const name = basename(path);
  if (SYNTAX_BY_NAME[name]) return SYNTAX_BY_NAME[name];
  if (name === 'Dockerfile' || name.startsWith('Dockerfile.') || name.endsWith('.Dockerfile')) return 'dockerfile';
  return SYNTAX_BY_EXTENSION[extname(name)];
}

export const isGenerated = (path, text) => GENERATED_NAMES.some((p) => p.test(path)) || GENERATED_HEADER.test(text.replace(/^﻿/, ''));

function lineAt(text, index) {
  let line = 1;
  for (let i = 0; i < index; i++) if (text[i] === '\n') line++;
  return line;
}

function skipQuoted(text, i, quote, escape) {
  for (let j = i + 1; j < text.length; j++) {
    if (escape && text[j] === '\\') j++;
    else if (escape && text[j] === '\n') return j;
    else if (text[j] === quote) return j + 1;
  }
  return text.length;
}

function skipCsharpString(text, i) {
  let start = i;
  while (text[start] === '$' || text[start] === '@') start++;
  const prefix = text.slice(i, start);
  let quotes = 0;
  while (text[start + quotes] === '"') quotes++;
  if (quotes >= 3) {
    const close = text.indexOf('"'.repeat(quotes), start + quotes);
    return close < 0 ? text.length : close + quotes;
  }
  if (prefix.includes('@')) {
    for (let j = start + 1; j < text.length; j++) {
      if (text[j] === '"' && text[j + 1] === '"') j++;
      else if (text[j] === '"') return j + 1;
    }
    return text.length;
  }
  return skipQuoted(text, start, '"', true);
}

function skipDollarQuoted(text, i) {
  const tag = text.slice(i).match(/^\$[A-Za-z_]*\$/)?.[0];
  if (!tag) return i + 1;
  const close = text.indexOf(tag, i + tag.length);
  return close < 0 ? text.length : close + tag.length;
}

function regexAllowed(text, i) {
  let j = i - 1;
  while (j >= 0 && /\s/.test(text[j])) j--;
  if (j < 0) return true;
  if (REGEX_AFTER.has(text[j])) return true;
  const word = text.slice(0, j + 1).match(/[A-Za-z_$][\w$]*$/)?.[0];
  return word !== undefined && REGEX_AFTER_WORDS.has(word);
}

function skipRegex(text, i) {
  let inClass = false;
  for (let j = i + 1; j < text.length && text[j] !== '\n'; j++) {
    if (text[j] === '\\') j++;
    else if (text[j] === '[') inClass = true;
    else if (text[j] === ']') inClass = false;
    else if (text[j] === '/' && !inClass) return j + 1;
  }
  return i + 1;
}

function scanCLike(text, { lineComments, regex, csharp, sql, quotes }) {
  const found = [];
  const templates = [];
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    const next = text[i + 1];
    const depth = templates.length ? templates[templates.length - 1] : undefined;
    if (depth !== undefined && c === '}' && depth === 0) {
      templates.pop();
      i = skipTemplate(text, i + 1, templates);
      continue;
    }
    if (depth !== undefined && c === '{') templates[templates.length - 1]++;
    else if (depth !== undefined && c === '}') templates[templates.length - 1]--;
    if (c === '/' && next === '*') {
      found.push(i);
      const close = text.indexOf('*/', i + 2);
      i = close < 0 ? text.length : close + 2;
    } else if (lineComments.some((marker) => text.startsWith(marker, i))) {
      found.push(i);
      const close = text.indexOf('\n', i);
      i = close < 0 ? text.length : close;
    } else if (csharp && (c === '"' || ((c === '$' || c === '@') && /^[$@]{1,2}"/.test(text.slice(i, i + 3))))) {
      i = skipCsharpString(text, i);
    } else if (sql && c === '$') {
      i = skipDollarQuoted(text, i);
    } else if (regex && c === '`') {
      i = skipTemplate(text, i + 1, templates);
    } else if (quotes.includes(c)) {
      i = skipQuoted(text, i, c, !sql);
    } else if (regex && c === '/' && regexAllowed(text, i)) {
      i = skipRegex(text, i);
    } else {
      i++;
    }
  }
  return found;
}

function skipTemplate(text, i, templates) {
  for (let j = i; j < text.length; j++) {
    if (text[j] === '\\') j++;
    else if (text[j] === '`') return j + 1;
    else if (text[j] === '$' && text[j + 1] === '{') {
      templates.push(0);
      return j + 2;
    }
  }
  return text.length;
}

function scanHash(text) {
  const found = [];
  let offset = 0;
  for (const line of text.split('\n')) {
    let quote;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      const boundary = i === 0 || /[\s:[{,]/.test(line[i - 1]);
      if (quote === '"' && c === '\\') i++;
      else if (quote && c === quote) quote = undefined;
      else if (!quote && (c === '"' || c === "'") && boundary) quote = c;
      else if (!quote && c === '#' && (i === 0 || /\s/.test(line[i - 1]))) {
        if (!(offset === 0 && i === 0 && line[1] === '!')) found.push(offset + i);
        break;
      }
    }
    offset += line.length + 1;
  }
  return found;
}

function scanDockerfile(text) {
  const found = [];
  let offset = 0;
  for (const line of text.split('\n')) {
    const indent = line.length - line.trimStart().length;
    if (line.trimStart().startsWith('#')) found.push(offset + indent);
    offset += line.length + 1;
  }
  return found;
}

const scanMarkup = (text) => [...text.matchAll(/<!--/g)].map((m) => m.index);

const SCANNERS = {
  script: (text) => scanCLike(text, { lineComments: ['//'], regex: true, quotes: ['"', "'"] }),
  csharp: (text) => scanCLike(text, { lineComments: ['//'], csharp: true, quotes: ["'"] }),
  css: (text) => scanCLike(text, { lineComments: [], quotes: ['"', "'"] }),
  sql: (text) => scanCLike(text, { lineComments: ['--'], sql: true, quotes: ['"', "'"] }),
  json: (text) => scanCLike(text, { lineComments: ['//'], quotes: ['"'] }),
  markup: scanMarkup,
  hash: scanHash,
  dockerfile: scanDockerfile,
};

export function findCommentLines(text, path) {
  const syntax = syntaxOf(path);
  if (!syntax || isGenerated(path, text)) return [];
  return [...new Set(SCANNERS[syntax](text)
    .filter((index) => !DIRECTIVE.test(text.slice(index, text.indexOf('\n', index) < 0 ? undefined : text.indexOf('\n', index))))
    .map((index) => lineAt(text, index)))];
}

export function parseArgs(argv) {
  const options = { root: '.', skip: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--skip' && argv[i + 1]) options.skip.push(argv[++i].replace(/\\/g, '/').replace(/\/$/, ''));
    else if (argv[i].startsWith('-')) throw new Error(`Unknown argument: ${argv[i]}\n${USAGE}`);
    else options.root = argv[i];
  }
  return options;
}

const skipped = (file, skip) => skip.some((path) => file === path || file.startsWith(`${path}/`));

export function findComments(files, read, skip = []) {
  const offenders = [];
  for (const file of files) {
    if (!syntaxOf(file) || skipped(file, skip)) continue;
    for (const line of findCommentLines(read(file).replace(/\r\n/g, '\n'), file)) offenders.push(`${file}:${line}`);
  }
  return offenders;
}

export function trackedFiles(root, run = execFileSync) {
  return run('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const options = parseArgs(process.argv.slice(2));
  const root = resolve(options.root);
  const offenders = findComments(trackedFiles(root), (file) => readFileSync(join(root, file), 'utf8'), options.skip);
  if (offenders.length > 0) {
    console.error(`Comments found (CLA-0035):\n${offenders.join('\n')}`);
    process.exit(1);
  }
}
