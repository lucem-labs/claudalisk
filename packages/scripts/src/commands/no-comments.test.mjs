test('finds Dockerfile comments but not parser directives or mid-line hashes', () => {
  const code = ['# syntax=docker/dockerfile:1', 'FROM node:22', '# why', 'RUN echo "#1"', '  # indented', ''].join('\n');
  assert.deepEqual(findCommentLines(code, 'Dockerfile'), [3, 5]);
});

test('the inheritdoc tag that EF Core writes is a directive only in migration files', () => {
  const code = '    /// <inheritdoc />\n    protected override void Up() {}\n';
  assert.deepEqual(findCommentLines(code, 'backend/App.Persistence/Migrations/20261024000000_Init.cs'), []);
  assert.deepEqual(findCommentLines(code, 'backend\\App.Persistence\\Migrations\\20261024000000_Init.cs'), []);
  assert.deepEqual(findCommentLines(code, 'backend/App.Domain/Order.cs'), [1]);
  assert.deepEqual(findCommentLines('/// <inheritdoc /> because\n', 'Migrations/20261024000000_Init.cs'), [1]);
});

test('findComments lists offenders as path:line and skips uncovered files', () => {
  const files = { 'a.ts': '// why\n', 'b.md': '<!-- docs -->\n', 'c.cs': 'class C {}\r\n// why\r\n' };
  assert.deepEqual(findComments(Object.keys(files), (f) => files[f]), [{ file: 'a.ts', line: 1 }, { file: 'c.cs', line: 2 }]);
});

test('findComments leaves out the skipped files and folders', () => {
  const files = { 'src/api/schema.ts': '// why\n', 'design/a.html': '<!-- why -->\n', 'designer.ts': '// why\n' };
  assert.deepEqual(findComments(Object.keys(files), (f) => files[f], ['src/api/schema.ts', 'design']), [{ file: 'designer.ts', line: 1 }]);
});

test('parseArgs reads the root and every --skip', () => {
  assert.deepEqual(parseArgs(['--skip', 'design/', '--skip', 'src\\api\\schema.ts']), { root: '.', skip: ['design', 'src/api/schema.ts'] });
  assert.deepEqual(parseArgs(['app']), { root: 'app', skip: [] });
  assert.throws(() => parseArgs(['--fix']), /Unknown argument: --fix/);
  assert.throws(() => parseArgs(['--skip']), /--skip needs a path/);
});

test('trackedFiles asks git for the tracked files with an argument array', () => {
  const calls = [];
  const run = (command, args, options) => {
    calls.push([command, args, options.cwd]);
    return 'a.ts\0dir/b.cs\0';
  };
  assert.deepEqual(trackedFiles('/repo', run), ['a.ts', 'dir/b.cs']);
  assert.deepEqual(calls, [['git', ['ls-files', '-z'], '/repo']]);
});

test('a closing JSX tag or a postfix operator does not start a regular expression', () => {
  assert.deepEqual(findCommentLines('const a = <b>x</b>; // why\n', 'a.tsx'), [1]);
  assert.deepEqual(findCommentLines('return <p>{a}</p>; /* why */\n', 'a.tsx'), [1]);
  assert.deepEqual(findCommentLines('const e = <Foo bar={x} />; // why\n', 'a.tsx'), [1]);
  assert.deepEqual(findCommentLines('const r = i++ / n; // why\n', 'a.ts'), [1]);
  assert.deepEqual(findCommentLines('const r = i-- / n; // why\n', 'a.ts'), [1]);
});

test('C# verbatim strings with quotes and interpolated raw strings', () => {
  assert.deepEqual(findCommentLines('var q = @"""";\n// why\n', 'A.cs'), [2]);
  assert.deepEqual(findCommentLines('var r = $$"""\n  {{x}} // no\n  """;\n// why\n', 'A.cs'), [4]);
});

test('SQL escape strings and dollar tags with digits', () => {
  assert.deepEqual(findCommentLines("select E'it\\'s -- no';\n-- why\n", 'fix.sql'), [2]);
  assert.deepEqual(findCommentLines('do $f1$ -- no\n$f1$;\n', 'fix.sql'), []);
});

test('YAML doubled quotes, multi-line quotes and block scalars', () => {
  assert.deepEqual(findCommentLines("name: 'it''s # fine'\n", 'a.yml'), []);
  assert.deepEqual(findCommentLines('d: "a\n  b # c"\ne: 1 # why\n', 'a.yml'), [3]);
  const code = ['steps:', '  - run: |', '      echo Issue #12', '', '      ## Steps', '  - name: x # why', 'body: >-', '  # heading', '# why', ''].join('\n');
  assert.deepEqual(findCommentLines(code, 'a.yml'), [6, 9]);
  assert.deepEqual(findCommentLines('#!/usr/bin/env yq\na: 1\n', 'a.yml'), []);
  assert.deepEqual(findCommentLines('a = "#x" # why\n', 'pyproject.toml'), [1]);
  const nginx = ['# why', 'server {', `    add_header X "a #b; 'self'" always;`, '    location ~ ^/(api|openapi)(/|$) {', '        try_files $uri =404; # why', '    }', '}', ''].join('\n');
  assert.deepEqual(findCommentLines(nginx, 'frontend/nginx.conf'), [1, 5]);
});

test('ignore files and .editorconfig take comments only at the start of a line', () => {
  assert.deepEqual(findCommentLines('# why\nbin/\nfile#1\n', '.gitignore'), [1]);
  assert.deepEqual(findCommentLines('root = true\n; why\n# why\n', '.editorconfig'), [2, 3]);
});

test('Dockerfile parser directives count only at the top', () => {
  assert.deepEqual(findCommentLines('FROM node:22\n# syntax=docker/dockerfile:1\n', 'Dockerfile'), [2]);
  assert.deepEqual(findCommentLines('# syntax=docker/dockerfile:1\n# escape=`\nFROM node:22\n', 'Dockerfile'), []);
});

function run(argv, files, env = {}) {
  const out = [];
  const err = [];
  const code = main(argv, { list: () => Object.keys(files), read: (_, f) => files[f], out: (t) => out.push(t), err: (t) => err.push(t), env });
  return { code, out, err };
}

test('main exits 0 when no tracked file has a comment', () => {
  assert.deepEqual(run([], { 'a.ts': 'export {};\n' }), { code: 0, out: [], err: [] });
});

test('main exits 1 and lists the offenders', () => {
  const result = run([], { 'a.ts': '// why\n' });
  assert.equal(result.code, 1);
  assert.deepEqual(result.out, []);
  assert.deepEqual(result.err, ['Comments found (CLA-0035):\na.ts:1']);
});

test('main annotates each offender in GitHub Actions', () => {
  const result = run(['--skip', 'vendor'], { 'a.ts': '// why\n', 'vendor/b.ts': '// theirs\n' }, { GITHUB_ACTIONS: 'true' });
  assert.equal(result.code, 1);
  assert.deepEqual(result.out, ['::error file=a.ts,line=1::Comment (CLA-0035)']);
});

test('main exits 2 on a usage error', () => {
  const result = run(['--nope'], {});
  assert.equal(result.code, 2);
  assert.match(result.err[0], /Unknown argument: --nope/);
});

test('a YAML comment that ends in a block indicator does not start a block scalar', () => {
  assert.deepEqual(findCommentLines('steps:  # list ->\n  # hidden\n', 'a.yml'), [1, 2]);
  assert.deepEqual(findCommentLines('# use a |\n  # hidden\n', 'a.yml'), [1, 2]);
});

test('an unbalanced quote inside a plain YAML value ends with its line', () => {
  assert.deepEqual(findCommentLines("a: b 'c\n# yes\n", 'a.yml'), [2]);
  assert.deepEqual(findCommentLines('run: echo "a # b"\n', 'a.yml'), []);
});

test('a regular expression that starts a line after a block is not division', () => {
  assert.deepEqual(findCommentLines('if (a) {}\n/^https?:\\/\\//.test(u)\n', 'a.js'), []);
});

test('Dockerfile parser directives are case-insensitive', () => {
  assert.deepEqual(findCommentLines('# SYNTAX=docker/dockerfile:1\nFROM x\n', 'Dockerfile'), []);
});

test('a dollar inside a SQL identifier is not a dollar quote', () => {
  assert.deepEqual(findCommentLines('select a$b$ -- c\n', 'fix.sql'), [1]);
});

test('parseArgs drops a leading ./ from --skip', () => {
  assert.deepEqual(parseArgs(['--skip', './design']).skip, ['design']);
});

test('the command reports a usage error as exit code 2', () => {
  const original = console.error;
  console.error = () => {};
  try {
    assert.equal(noComments({ argv: ['--nope'], env: {} }), 2);
  } finally {
    console.error = original;
  }
});
